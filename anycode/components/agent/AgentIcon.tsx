interface AgentIconProps {
    name?: string;
    id?: string;
    size?: number;
    className?: string;
}

export const AgentIcon: React.FC<AgentIconProps> = ({
    name = '',
    id = '',
    size = 16,
    className = '',
}) => {
    const checkStr = `${name} ${id}`.toLowerCase();

    if (checkStr.includes('gemini')) {
        return <GeminiIcon size={size} className={className} />;
    }
    if (checkStr.includes('claude')) {
        return <ClaudeIcon size={size} className={className} />;
    }
    if (checkStr.includes('qwen')) {
        return <QwenIcon size={size} className={className} />;
    }
    if (
        checkStr.includes('codex') ||
        checkStr.includes('openai') ||
        checkStr.includes('gpt') ||
        checkStr.includes('chatgpt')
    ) {
        return <CodexIcon size={size} className={className} />;
    }
    if (checkStr.includes('deepseek')) {
        return <DeepSeekIcon size={size} className={className} />;
    }
    if (
        checkStr.includes('opencode') ||
        checkStr.includes('coder') ||
        checkStr.includes('local')
    ) {
        return <OpenCodeIcon size={size} className={className} />;
    }
    if (checkStr.includes('grok')) {
        return <GrokIcon size={size} className={className} />;
    }

    return <DefaultSparkleIcon size={size} className={className} />;
};
